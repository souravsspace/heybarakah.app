/**
 * Silences the Xcode build warning:
 *
 *   "Script has ambiguous dependencies causing it to run on every build.
 *    ... '[Expo Dev Launcher] Strip Local Network Keys for Release' ...
 *    Either: Uncheck 'Based on dependency analysis', or select output files"
 *
 * expo-dev-launcher injects a `[Expo Dev Launcher] Strip Local Network Keys for
 * Release` shell-script build phase with no input/output paths, so Xcode can't
 * infer when to run it and warns on every build. The phase edits Info.plist at
 * build time and legitimately has to run every build, so the correct fix is
 * `alwaysOutOfDate = 1` (exactly what unchecking "Based on dependency analysis"
 * sets) — the sibling `[Expo] Configure project` phase already carries it.
 *
 * `ios/` is regenerated by prebuild, so this runs as a `finalized` on-disk pass
 * (after every other mod) and rewrites the generated project.pbxproj.
 */
const fs = require("node:fs");
const path = require("node:path");
const { withMod } = require("expo/config-plugins");

const PHASE_NAME = "[Expo Dev Launcher] Strip Local Network Keys for Release";

/**
 * Insert `alwaysOutOfDate = 1;` into the Strip Local Network Keys shell-script
 * phase if it isn't already there.
 */
function patchStripPhase(pbxprojPath) {
  if (!fs.existsSync(pbxprojPath)) {
    return;
  }
  const contents = fs.readFileSync(pbxprojPath, "utf8");

  // Match the phase's object block: its guid/comment header down to `isa`.
  // Anchoring on the phase name avoids touching any other shell-script phase.
  const anchor = new RegExp(
    `(/\\* ${PHASE_NAME.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")} \\*/ = \\{\\s*\\n\\s*isa = PBXShellScriptBuildPhase;\\n)`
  );
  const match = contents.match(anchor);
  if (!match) {
    return;
  }
  const block = match[1];
  if (block.includes("alwaysOutOfDate")) {
    return;
  }
  const indent = "\t\t\t";
  const patched = contents.replace(
    block,
    `${block}${indent}alwaysOutOfDate = 1;\n`
  );
  if (patched !== contents) {
    fs.writeFileSync(pbxprojPath, patched);
  }
}

module.exports = function withStripLocalNetworkScript(config) {
  return withMod(config, {
    platform: "ios",
    mod: "finalized",
    action: (cfg) => {
      const iosRoot = cfg.modRequest.platformProjectRoot;
      const projectDir = fs
        .readdirSync(iosRoot)
        .find((name) => name.endsWith(".xcodeproj"));
      if (projectDir) {
        patchStripPhase(path.join(iosRoot, projectDir, "project.pbxproj"));
      }
      return cfg;
    },
  });
};
